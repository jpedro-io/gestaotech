--     python manage.py migrate --fake-initial
-- para o Django saber que as tabelas já existem.
--
-- Privacidade: o CPF NUNCA é gravado. Vão para o banco apenas
--   cpf_hash  = SHA-256(cpf + CPF_PEPPER do .env)  -> usado na busca
--   cpf_meio  = os 6 dígitos do meio do CPF        -> exibe ***.982.247-**
-- ============================================================================

CREATE TABLE IF NOT EXISTS certificados_oficina (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        varchar(200) NOT NULL UNIQUE,
    equipe      varchar(300) NOT NULL DEFAULT '',
    criado_em   timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS certificados_participacao (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        varchar(160) NOT NULL,
    cpf_hash    varchar(64)  NOT NULL DEFAULT '',   -- vazio = CPF ainda não informado
    cpf_meio    varchar(6)   NOT NULL DEFAULT '',
    papel       varchar(12)  NOT NULL DEFAULT 'OUVINTE',
    codigo      varchar(18)  NOT NULL UNIQUE,       -- OFC-XXXX-XXXX-XXXX (QR Code)
    revogado    boolean      NOT NULL DEFAULT false,
    emitido_em  date         NULL,                  -- 1ª emissão do PDF
    criado_em   timestamptz  NOT NULL DEFAULT now(),
    oficina_id  bigint       NOT NULL
                REFERENCES certificados_oficina (id)
                ON DELETE RESTRICT DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT participacao_papel_check
        CHECK (papel IN ('OUVINTE', 'MINISTRANTE', 'ORGANIZADOR'))
);

-- a mesma pessoa pode ter um certificado por oficina/papel, mas não dois iguais
CREATE UNIQUE INDEX IF NOT EXISTS unico_cpf_oficina_papel
    ON certificados_participacao (cpf_hash, oficina_id, papel)
    WHERE cpf_hash <> '';

CREATE INDEX IF NOT EXISTS certificados_participacao_cpf_hash_idx
    ON certificados_participacao (cpf_hash);

CREATE INDEX IF NOT EXISTS certificados_participacao_codigo_idx
    ON certificados_participacao (codigo);

CREATE INDEX IF NOT EXISTS certificados_participacao_oficina_id_idx
    ON certificados_participacao (oficina_id);
